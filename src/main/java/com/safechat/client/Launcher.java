package com.safechat.client;

/**
 * Bootstrap launcher for the SafeChat JavaFX client application.
 */
public class Launcher {

    /**
     * Application entry point delegating to {@link ClientGUI#main(String[])}.
     *
     * @param args command-line arguments passed to the JavaFX runtime
     */
    public static void main(String[] args) {
        ClientGUI.main(args);
    }
}
